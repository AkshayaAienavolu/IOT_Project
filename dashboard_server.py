@app.route('/user/<user_id>')
def user_dashboard(user_id):
    """Display dashboard for specific user"""
    # Prefer exact folder, otherwise try to find a best match by suffix
    user_dir = os.path.join(DASHBOARD_DIR, user_id)
    displayed_user_id = user_id
    if not os.path.exists(user_dir):
        matched = find_best_user_match(user_id)
        if matched and matched != user_id:
            user_dir = os.path.join(DASHBOARD_DIR, matched)
            displayed_user_id = matched
        else:
            return f"No dashboard found for user {user_id}. Click 'Regenerate Dashboards' to create charts.", 404

    # Get list of chart files (including integrated sensor charts)
    charts = []
    chart_files = [
        'integrated_timeline.png',      # Integrated: HR + Emotions
        'hr_by_emotion.png',            # Integrated: HR distribution by emotion
        'spo2_timeline.png',            # Integrated: Blood oxygen
        'emotion_distribution.png',     # Original: Emotion counts
        'timeline.png',                 # Original: Emotion timeline
        'confidence.png',               # Original: Confidence
        'hourly_activity.png'           # Original: Activity by hour
    ]
    for chart_file in chart_files:
        chart_path = os.path.join(user_dir, chart_file)
        if os.path.exists(chart_path):
            charts.append({
                'name': chart_file.replace('.png', '').replace('_', ' ').title(),
                'url': f'/dashboards/{displayed_user_id}/{chart_file}'
            })

    # Read summary text if exists (contains wellbeing suggestions)
    summary_path = os.path.join(user_dir, 'summary.txt')
    summary = None
    if os.path.exists(summary_path):
        with open(summary_path, 'r') as f:
            summary = f.read()

    # If we matched to a different id, add a small notice
    if displayed_user_id != user_id:
        note = f"Note: showing data for '{displayed_user_id}' which closely matches your id '{user_id}'." \
               " If you believe this is incorrect, please contact the admin."
        summary = (note + '\n\n' + summary) if summary else note

    return render_template('user_dashboard.html', 
                          user_id=displayed_user_id, 
                          charts=charts, 
                          summary=summary)

@app.route('/api/user/<user_id>/summary')
def api_user_summary(user_id):
    """API endpoint to get user's dashboard data as JSON"""
    try:
        # Check if user exists in database
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute("""
            SELECT COUNT(*) as total, 
                   emotion,
                   AVG(confidence) as avg_conf,
                   MIN(ts_received) as first_seen,
                   MAX(ts_received) as last_seen
            FROM events 
            WHERE user_id = ?
            GROUP BY user_id, emotion
            ORDER BY total DESC
        """, (user_id,))
        
        rows = cursor.fetchall()
        conn.close()
        
        if not rows:
            # Try to find a closely matching user id (suffix match)
            matched = find_best_user_match(user_id)
            if matched and matched != user_id:
                # re-run query for matched user
                conn = sqlite3.connect(DB_PATH)
                cursor = conn.cursor()
                cursor.execute("""
                    SELECT COUNT(*) as total, 
                           emotion,
                           AVG(confidence) as avg_conf,
                           MIN(ts_received) as first_seen,
                           MAX(ts_received) as last_seen
                    FROM events 
                    WHERE user_id = ?
                    GROUP BY user_id, emotion
                    ORDER BY total DESC
                """, (matched,))
                rows = cursor.fetchall()
                conn.close()
                # If still empty, return not found
                if not rows:
                    return jsonify({'error': 'User not found'}), 404
                # use matched id for response
                used_user_id = matched
            else:
                return jsonify({'error': 'User not found'}), 404
        else:
            used_user_id = user_id
        
        # Calculate stats
        total_events = sum(row[0] for row in rows)
        top_emotion = rows[0][1] if rows else 'Unknown'
        avg_confidence = int(sum(row[2] for row in rows) / len(rows))
        first_seen = rows[0][3]
        last_seen = rows[0][4]
        
        # Calculate days active
        from datetime import datetime
        try:
            first = datetime.fromisoformat(first_seen.replace('Z', '+00:00'))
            last = datetime.fromisoformat(last_seen.replace('Z', '+00:00'))
            days_active = max(1, (last - first).days + 1)
        except:
            days_active = 1
        
        # Check if charts exist
        user_dir = os.path.join(DASHBOARD_DIR, user_id)
        charts = []
        chart_files = ['emotion_distribution.png', 'timeline.png', 'confidence.png', 'hourly_activity.png']
        for chart_file in chart_files:
            chart_path = os.path.join(user_dir, chart_file)
            if os.path.exists(chart_path):
                charts.append({
                    'name': chart_file.replace('.png', '').replace('_', ' ').title(),
                    'url': f'/dashboards/{user_id}/{chart_file}'
                })
        
        # Read summary
        summary_path = os.path.join(user_dir, 'summary.txt')
        summary = None
        if os.path.exists(summary_path):
            with open(summary_path, 'r') as f:
                summary = f.read()
        
        return jsonify({
            'user_id': used_user_id,
            'stats': {
                'total_events': total_events,
                'top_emotion': top_emotion,
                'avg_confidence': avg_confidence,
                'days_active': days_active
            },
            'charts': charts,
            'summary': summary
        })
        
    except Exception as e:
        return jsonify({'error': str(e)}), 500

