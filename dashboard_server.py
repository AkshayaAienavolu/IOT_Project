def get_all_users():
    """Fetch list of all user IDs from database"""
    try:
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute("""
            SELECT DISTINCT user_id, COUNT(*) as event_count, 
                   MIN(ts_received) as first_seen, 
                   MAX(ts_received) as last_seen
            FROM events
            GROUP BY user_id
            ORDER BY last_seen DESC
        """)
        users = []
        for row in cursor.fetchall():
            users.append({
                'user_id': row[0],
                'event_count': row[1],
                'first_seen': row[2],
                'last_seen': row[3]
            })
        conn.close()
        return users
    except Exception as e:
        print(f"Error fetching users: {e}")
        return []

def find_best_user_match(requested_id):
    """Try to find a close matching user id in the database.
    - Return requested_id if it exists
    - Otherwise try suffix matching and return the most-recent user if found
    - Return None if no match
    """
    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.cursor()

        # Exact match first
        cur.execute("SELECT DISTINCT user_id FROM events WHERE user_id = ?", (requested_id,))
        row = cur.fetchone()
        if row:
            conn.close()
            return requested_id

        # Suffix match: use last segment after underscore or last 8 chars
        suffix = requested_id.split('_')[-1]

        # Look for any user_id that ends with the same suffix, pick most recent activity
        cur.execute("""
            SELECT user_id, MAX(ts_received) as last_seen
            FROM events
            WHERE user_id LIKE ? OR user_id LIKE ?
            GROUP BY user_id
            ORDER BY last_seen DESC
            LIMIT 1
        """, (f"%{suffix}", f"%{suffix[-8:]}"))
        row = cur.fetchone()
        conn.close()
        if row:
            return row[0]
    except Exception as e:
        print(f"Error in find_best_user_match: {e}")
    return None

def regenerate_dashboards():
    """Regenerate all dashboard charts (now uses integrated dashboard)"""
    try:
        # Run the INTEGRATED dashboard generator (emotion + sensor data)
        # This creates comprehensive mental-state reports with vitals
        result = subprocess.run(
            ['python3', DASHBOARD_SCRIPT, DB_PATH],
            cwd=BASE_DIR,
            capture_output=True,
            text=True,
            timeout=60
        )
        return {
            'success': result.returncode == 0,
            'stdout': result.stdout,
            'stderr': result.stderr
        }
    except Exception as e:
        return {
            'success': False,
            'error': str(e)
        }

